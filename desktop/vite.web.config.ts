function findWasm(): string {
  const rel = path.resolve(here, 'web-wasm/target/wasm32-wasip1/release/tiffin_web_wasm.wasm')
  if (fs.existsSync(rel)) return rel
  const dbg = path.resolve(here, 'web-wasm/target/wasm32-wasip1/debug/tiffin_web_wasm.wasm')
  if (fs.existsSync(dbg)) return dbg
  throw new Error('tiffin_web_wasm.wasm not found; build desktop/web-wasm for wasm32-wasip1 first.')
}

function buildServiceWorker(version: string, precache: string[]): string {
  return `// Tiffin offline app-shell service worker (generated by vite.web.config.ts).
// Each deploy builds an immutable, content-hashed cache of same-origin shell assets
// (HTML, JS, CSS, workers, icons, manifest, and tiffin.wasm) with COOP/COEP intact.
const PREFIX = 'tiffin-shell-';
const CACHE = ${JSON.stringify(`tiffin-shell-${version}`)};
const PRECACHE = ${JSON.stringify(precache)};

let precached = null;
function precacheSet() {
  if (!precached) {
    precached = new Set(PRECACHE.map((u) => new URL(u, self.registration.scope).href));
  }
  return precached;
}

function shellHref() {
  return new URL('./', self.registration.scope).href;
}

function cacheable(res) {
  return res.status === 200 && res.type === 'basic' && !res.redirected;
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const urls = PRECACHE.map((u) => new URL(u, self.registration.scope).href);
    await Promise.all(urls.map(async (href) => {
      const res = await fetch(new Request(href, { cache: 'reload' }));
      if (!cacheable(res)) throw new Error('Uncacheable precache response: ' + href + ' (' + res.status + ')');
      await cache.put(href, res);
    }));
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k)))),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    const privacyUrl = new URL('./privacy/', self.registration.scope);
    const privacyNoSlash = privacyUrl.pathname.endsWith('/') ? privacyUrl.pathname.slice(0, -1) : privacyUrl.pathname;
    const privacyHtmlPath = privacyNoSlash + '.html';
    const isPrivacy =
      url.pathname === privacyUrl.pathname ||
      url.pathname === privacyNoSlash ||
      url.pathname === privacyHtmlPath ||
      url.pathname === privacyUrl.pathname + 'index.html';
    const target = isPrivacy ? privacyUrl.href : shellHref();
    event.respondWith(
      caches.match(target, { cacheName: CACHE, ignoreVary: true })
        .then((hit) => hit || fetch(req).catch(() => Response.error())),
    );
    return;
  }

  if (!precacheSet().has(url.href)) return;
  event.respondWith(
    caches.match(url.href, { cacheName: CACHE, ignoreVary: true })
      .then((hit) => hit || fetch(req).catch(() => Response.error())),
  );
});
`
}

function webTransportPlugin(helperOrigin: string): Plugin {
  const desktopTransport = norm(path.resolve(here, 'src/lib/transport.ts'))
  const webTransport = norm(path.resolve(here, 'src/web/transport.ts'))
  const previewAppCsp = buildAppCsp(helperOrigin, false)
  const previewPrivacyCsp = buildPrivacyCsp(false)
  return {
    name: 'tiffin-web-transport',
    enforce: 'pre',
    async resolveId(source, importer, opts) {
      if (!importer || !source.includes('transport')) return null
      const resolved = await this.resolve(source, importer, { ...opts, skipSelf: true })
      if (resolved && norm(resolved.id.split('?')[0]) === desktopTransport) {
        return webTransport
      }
      return null
    },
    transformIndexHtml() {
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: '/manifest.webmanifest' }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: '/icons/apple-touch-icon.png' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#fff6e9', media: '(prefers-color-scheme: light)' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#2b2118', media: '(prefers-color-scheme: dark)' }, injectTo: 'head' },
      ]
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const pathname = (req.url ?? '').split('?')[0]
        if (pathname === '/manifest.webmanifest') {
          if (req.method !== 'GET' && req.method !== 'HEAD') {
            res.statusCode = 405
            res.setHeader('Allow', 'GET, HEAD')
            res.end()
            return
          }
          const body = Buffer.from(manifestJson, 'utf8')
          res.setHeader('Content-Type', 'application/manifest+json; charset=utf-8')
          res.setHeader('Content-Length', String(body.length))
          res.setHeader('Cross-Origin-Resource-Policy', 'same-origin')
          res.setHeader('Cache-Control', 'no-cache')
          res.end(req.method === 'HEAD' ? undefined : body)
          return
        }
        const pageKey = pathname === '/privacy' || pathname === '/privacy/' || pathname === '/privacy.html'
          ? 'privacy/index.html'
          : pathname.startsWith('/') ? pathname.slice(1) : pathname
        if (Object.hasOwn(staticWebPages, pageKey)) {
          if (req.method !== 'GET' && req.method !== 'HEAD') {
            res.statusCode = 405
            res.setHeader('Allow', 'GET, HEAD')
            res.end()
            return
          }
          try {
            const { file, contentType } = staticWebPages[pageKey]
            const data = fs.readFileSync(file)
            res.setHeader('Content-Type', contentType)
            res.setHeader('Content-Length', String(data.length))
            res.setHeader('Cross-Origin-Resource-Policy', 'same-origin')
            res.setHeader('Cache-Control', 'no-cache')
            res.end(req.method === 'HEAD' ? undefined : data)
          } catch (e) {
            next(e)
          }
          return
        }
        const iconKey = pathname.startsWith('/') ? pathname.slice(1) : pathname
        if (Object.hasOwn(pwaIcons, iconKey)) {
          if (req.method !== 'GET' && req.method !== 'HEAD') {
            res.statusCode = 405
            res.setHeader('Allow', 'GET, HEAD')
            res.end()
            return
          }
          try {
            const data = fs.readFileSync(pwaIcons[iconKey])
            res.setHeader('Content-Type', 'image/png')
            res.setHeader('Content-Length', String(data.length))
            res.setHeader('Cross-Origin-Resource-Policy', 'same-origin')
            res.end(req.method === 'HEAD' ? undefined : data)
          } catch (e) {
            next(e)
          }
          return
        }
        if (pathname !== '/tiffin.wasm') return next()
        if (req.method !== 'GET' && req.method !== 'HEAD') {
          res.statusCode = 405
          res.setHeader('Allow', 'GET, HEAD')
          res.end()
          return
        }
        try {
          const file = findWasm()
          const stat = fs.statSync(file)
          res.setHeader('Content-Type', 'application/wasm')
          res.setHeader('Content-Length', String(stat.size))
          res.setHeader('Cross-Origin-Resource-Policy', 'same-origin')
          res.setHeader('Cache-Control', 'no-cache')
          if (req.method === 'HEAD') {
            res.end()
            return
          }
          const stream = fs.createReadStream(file)
          stream.on('error', (err) => {
            if (!res.headersSent) next(err)
            else res.destroy(err)
          })
          stream.pipe(res)
        } catch (e) {
          next(e)
        }
      })
    },
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => {
        const rawUrl = req.url ?? '/'
        const qIdx = rawUrl.indexOf('?')
        const rawPath = qIdx === -1 ? rawUrl : rawUrl.slice(0, qIdx)
        const query = qIdx === -1 ? '' : rawUrl.slice(qIdx)
        let pathname = rawPath
        try {
          pathname = decodeURIComponent(rawPath)
        } catch {
          res.statusCode = 400
          for (const [k, v] of Object.entries(isolated)) res.setHeader(k, v)
          res.end()
          return
        }
        if (pathname === '/_headers') {
          res.statusCode = 404
          for (const [k, v] of Object.entries(isolated)) res.setHeader(k, v)
          res.setHeader('Cache-Control', 'no-cache')
          res.end()
          return
        }
        if (pathname === '/privacy' || pathname === '/privacy/' || pathname === '/privacy.html' || pathname === '/privacy/index.html') {
          if (pathname === '/privacy' || pathname === '/privacy.html') {
            req.url = `/privacy/index.html${query}`
          }
          res.setHeader('Content-Security-Policy', previewPrivacyCsp)
          res.setHeader('Permissions-Policy', PRIVACY_PERMISSIONS_POLICY)
          res.setHeader('Cache-Control', 'no-cache')
        } else {
          res.setHeader('Content-Security-Policy', previewAppCsp)
          res.setHeader('Permissions-Policy', APP_PERMISSIONS_POLICY)
          res.setHeader('Cache-Control', pathname.startsWith('/assets/') ? 'public, max-age=31536000, immutable' : 'no-cache')
        }
        next()
      })
    },
  }
}

function webPwaBundlePlugin(helperOrigin: string): Plugin {
  return {
    name: 'tiffin-web-pwa-bundle',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = new Map<string, Uint8Array | string>()
      const addAsset = (fileName: string, source: Uint8Array | string) => {
        this.emitFile({ type: 'asset', fileName, source })
        files.set(fileName, source)
      }

      addAsset('tiffin.wasm', fs.readFileSync(findWasm()))
      addAsset('manifest.webmanifest', manifestJson)
      for (const [fileName, srcPath] of Object.entries(pwaIcons)) {
        addAsset(fileName, fs.readFileSync(srcPath))
      }
      for (const [fileName, { file }] of Object.entries(staticWebPages)) {
        addAsset(fileName, fs.readFileSync(file))
      }

      for (const f of publicStatic) {
        const full = path.resolve(here, 'public', f)
        if (fs.existsSync(full)) files.set(f, fs.readFileSync(full))
      }

      for (const [fileName, item] of Object.entries(bundle)) {
        if (fileName === 'sw.js' || fileName.endsWith('.map')) continue
        files.set(fileName, item.type === 'chunk' ? item.code : item.source)
      }

      const hash = crypto.createHash('sha256')
      const precache: string[] = ['./']
      for (const fileName of [...files.keys()].sort()) {
        hash.update(fileName)
        hash.update(files.get(fileName)!)
        if (fileName === 'index.html') continue
        // Precache directory index pages as canonical "./dir/" so Pretty-URL hosts return 200 without redirecting.
        if (fileName.endsWith('/index.html')) {
          precache.push(`./${fileName.slice(0, -'index.html'.length)}`)
        } else {
          precache.push(`./${fileName}`)
        }
      }

      const version = hash.digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: buildServiceWorker(version, precache) })
      // Emit host header config after computing the SW precache list so _headers is never precached.
      this.emitFile({ type: 'asset', fileName: '_headers', source: buildCloudflareHeaders(helperOrigin) })
    },
  }
}

export default defineConfig(({ mode, command }) => {
  const env = loadEnv(mode, here, 'VITE_')
  const helperOrigin = resolveHelperOrigin(env.VITE_HELPER_URL || process.env.VITE_HELPER_URL, command === 'build')
  return {
    plugins: [webTransportPlugin(helperOrigin), svelte(), webPwaBundlePlugin(helperOrigin)],
    clearScreen: false,
    build: { outDir: 'dist-web' },
    server: {
      port: 5174,
      strictPort: true,
      headers: isolated,
      // the test pages load recipe_box's wasm test binary straight from its build folder
      fs: { allow: ['.', '../app/target/wasm32-wasip1', 'web-wasm/target/wasm32-wasip1'] },
    },
    preview: { headers: isolated },
    worker: { format: 'es' },
  }
})
