const norm = (p: string) => p.replace(/\\/g, '/')

// The web build (Milestone 2). Separate from vite.config.ts: the desktop window must not be cross-origin
// isolated (COEP would block its photo:// pictures), but the web version needs it for SharedArrayBuffer,
// which the OPFS sync bridge (src/web/wasi-opfs.ts) runs on.
const DEFAULT_HELPER_ORIGIN = 'https://helper.tiffin.fyi'
const OFF_PRODUCT_ORIGIN = 'https://world.openfoodfacts.org'
const HSTS_RAMP = 'max-age=300; includeSubDomains'
const APP_PERMISSIONS_POLICY = 'camera=(self), screen-wake-lock=(self), microphone=(), geolocation=(), payment=(), usb=()'
const PRIVACY_PERMISSIONS_POLICY = 'camera=(), screen-wake-lock=(), microphone=(), geolocation=(), payment=(), usb=()'

function isSafeCspHost(hostname: string): boolean {
  // Strict RFC hostname, IPv4, or bracketed IPv6 — rejects CSP metacharacters (; * ' , " whitespace).
  if (/^\[[0-9a-fA-F:]+\]$/.test(hostname)) return true
  if (/^\d{1,3}(\.\d{1,3}){3}$/.test(hostname)) return true
  return /^[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*$/.test(hostname)
}

function isLoopbackHost(hostname: string): boolean {
  return hostname === 'localhost' || hostname === '127.0.0.1' || hostname === '[::1]'
}

function resolveHelperOrigin(rawValue: string | undefined, requireHttpsForRemote: boolean): string {
  const raw = String(rawValue ?? '').trim()
  if (!raw) return DEFAULT_HELPER_ORIGIN
  let u: URL
  try {
    u = new URL(raw)
  } catch {
    throw new Error(`Invalid VITE_HELPER_URL (${JSON.stringify(raw)}): must be an http(s) origin.`)
  }
  if ((u.protocol !== 'http:' && u.protocol !== 'https:') || u.username || u.password || u.search || u.hash || !isSafeCspHost(u.hostname)) {
    throw new Error(`Invalid VITE_HELPER_URL (${JSON.stringify(raw)}): must be a clean http(s) origin without credentials, query, hash, or special host characters.`)
  }
  if (requireHttpsForRemote && u.protocol !== 'https:' && !isLoopbackHost(u.hostname)) {
    throw new Error(`Invalid VITE_HELPER_URL (${JSON.stringify(raw)}): production helper origin must use https://.`)
  }
  return u.origin
}

function buildAppCsp(helperOrigin: string, upgradeInsecure: boolean): string {
  const parts = [
    "default-src 'self'",
    "script-src 'self' 'wasm-unsafe-eval'",
    "worker-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self'",
    `connect-src 'self' ${OFF_PRODUCT_ORIGIN} ${helperOrigin}`,
    "manifest-src 'self'",
    "media-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-src 'none'",
    "frame-ancestors 'none'",
  ]
  if (upgradeInsecure) parts.push('upgrade-insecure-requests')
  return parts.join('; ')
}

function buildPrivacyCsp(upgradeInsecure: boolean): string {
  const parts = [
    "default-src 'none'",
    "style-src 'self'",
    "img-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
  ]
  if (upgradeInsecure) parts.push('upgrade-insecure-requests')
  return parts.join('; ')
}

const isolated: Record<string, string> = {
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Embedder-Policy': 'require-corp',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'no-referrer',
}

function buildCloudflareHeaders(origin: string): string {
  // Cloudflare Pages _headers: rules apply in order; "! Header" detaches an inherited header before overriding.
  // HSTS starts at 300s for initial HTTPS verification; raise to max-age=31536000; includeSubDomains once verified.
  const privCsp = buildPrivacyCsp(true)
  return `# Generated by desktop/vite.web.config.ts for Cloudflare Pages.
/*
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Embedder-Policy: require-corp
  Cross-Origin-Resource-Policy: same-origin
  Content-Security-Policy: ${buildAppCsp(origin, true)}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: ${APP_PERMISSIONS_POLICY}
  Strict-Transport-Security: ${HSTS_RAMP}
  Cache-Control: no-cache

/privacy
  ! Content-Security-Policy
  Content-Security-Policy: ${privCsp}
  ! Permissions-Policy
  Permissions-Policy: ${PRIVACY_PERMISSIONS_POLICY}

/privacy/*
  ! Content-Security-Policy
  Content-Security-Policy: ${privCsp}
  ! Permissions-Policy
  Permissions-Policy: ${PRIVACY_PERMISSIONS_POLICY}

/assets/*
  ! Cache-Control
  Cache-Control: public, max-age=31536000, immutable
`
}

